app.delete('/tasks/:id', authenticateToken, async (req, res) => //Метод для операции УДАЛЕНИЕ
    {
        const currentUserId = req.user.userId; //ловим айди пользователя, подавшего запрос, вставляем её в переменную currentUserId
        const id = Number(req.params.id); //принимает введённый номер пользователем как айди при запросе delete .../tasks/id (вместо айди вводит цифру)
        // В блок try мы кладем код, который ХОТИМ ПОПРОБОВАТЬ выполнить
        try {
                const deletedTask = await prisma.task.delete //метод для удаления записи, принимает внутрь объект 'where' которое означает "где/при условии что"
                (
                    {
                        where:
                            {
                                id:id,
                                userId:currentUserId
                            }
                    }
                )
                return res.send (`Задача: {"${deletedTask.id}" - "${deletedTask.text}"} успешно удалена!`); //выводит текст, айди задачи, текст, текст задачи, текст   
            }
        // Если Призма выдала ошибку (запись не найдена), код мгновенно прыгает в блок catch!
        catch (error) 
            {
                // Ловим ошибку и вместо падения сервера отдаем аккуратный статус 404 (Не найдено)
                return res.status(404).send({ error: "Задача не найдена или доступ запрещен" });
            }   
    })

