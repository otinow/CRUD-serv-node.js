app.post('/register', async (req, res) => //(для регистрации пользователей)
    {
        const { email, password } = req.body; //достаём из тела запроса email и password
        // это сокращение от двух строчек: 
        // const email = req.body.email;
        // const password = req.body.password;
        // то есть мы принимаем в теле объекта переменные email и password одной командой 
        // красивый, лаконичный способ распаковать объект в отдельные переменные за один шаг

        const hashedPassword = await bcrypt.hash(password, 10); // Число 10 — это "соль" (количество раундов шифрования). 
        // Чем выше, тем надежнее, но 10 — это золотой стандарт скорости и защиты.
        // На этом этапе мы хэшируем полученный от пользователя пароль
        const newUser = await prisma.user.create //метод для создания юзеров, в него мы записываем email и хэш.пароль hashedPassword
        (
            {
                data:
                    {
                        email:email,
                        password: hashedPassword // Записываем в базу именно ХЕШ, а не чистый пароль!
                    }
            }
        )
        return res.send(`Пользователь'${newUser.email},' успешно зарегистрирован!` );
    }) 


