app.post('/login', async (req, res) => //(для аутентификации пользователей)
    {
        const { email, password } = req.body; //достаём из тела запроса email и password
        //const { email, password } = req.query; //для проверки в браузере
        const user = await prisma.user.findUnique //проверить, есть ли вообще такой имейл в базе данных
        ({
            where: { email: email }
        });
        if (!user)
        {
            return res.status(400).send({ error: "Неверный email или пароль" }); //в случае несхождения юзера возвращает ошибку, функция останавливается
        }
            
        const isMatch = await bcrypt.compare(password, user.password); //bcrypt возьмет присланный пароль, захеширует его с теми же настройками и сравнит получившиеся хеши
        //подробнее:
        //1. берёт user.password (это старый хэш пароля от этого же пользователя, который он получил когда тот регистрировался);
        //2. из старого хэша он берёт версию алгоритма, (например, 2а), кол-во раундов перемешивания (10, 2^10=1024 раза), добавляет соль (билиберду символов приплетает)
        //3. берёт password (новый пароль который тока что получил от пользователя) и делает всё то же самое что во втором пункте;
        //4. если пароли совпадают, то и хэш у них будет совпадать
        
        if (!isMatch)
        {
            return res.status(400).send({ error: "Неверный email или пароль" }); //в случае несхождения пароля возвращает ошибку, функция останавливается
        }
                
        const token = jwt.sign //Создание «Пропуска» (JWT): Если всё совпало, создаем токен
        //подробнее:
        //1. Когда пользователь успешно ввел пароль, мы берем его уникальный номер из базы данных (например, id: 5) и прячем в токен
        // Эта часть токена (секретный ключ "userId: user.id") не зашифрована намертво. 
        // Закодирована в специальный текстовый формат (Base64)
        // Перехвативший токен, может зайти на сайт jwt.io
        // Вставить его туда и прочитать: «Ага, внутри лежит userId: 5»
        // Правило безопасности: 
        // Из-за этого внутрь токена категорически нельзя класть секретные данные: 
        // пароли, номера карт или личные телефоны. 
        // Туда кладут только открытые идентификаторы (ID, email, роль пользователя).

        //2. Это длинная секретная строка (пароль), которую знает только ваш сервер. 
        // Она хранится в файле .env и никогда не отправляется пользователю.
        // На основе этого секретного слова 'СЕКРЕТНОЕ_СЛОВО_ДЛЯ_ПОДПИСИ' алгоритм Призмы/JWT берет ваши данные (userId: 5), 
        // смешивает их с секретным словом и генерирует третью часть токена — Цифровую подпись (Signature)

        (
            { 
                userId: user.id // Что зашифровать внутрь токена (наша полезная нагрузка)
            }, 
                'СЕКРЕТНОЕ_СЛОВО_ДЛЯ_ПОДПИСИ', // Секретный ключ сервера, который знаем только мы
            { 
                expiresIn: '1h' // Срок годности токена (например, 1 час)
            } 
        );

        // Отправляем токен в куки под именем 'token'
        return res.cookie ('token', token,  //'имя_куки_в_браузере', значение_которое_туда_кладем { настройки }
            {
                httpOnly: true, // ГЛАВНОЕ ПРАВИЛО: защищает куку от кражи скриптами прячет эту куку в изолированный системный контейнер
                // Временно комментируем эту строку для локального теста в консоли:
                secure: process.env.NODE_ENV === 'production', // Кука передается только по защищенному HTTPS (включаем только на живом сервере)
                // решает проблему: как сделать так, чтобы код работал и на компьютере программиста, и на живом защищенном сайте, не меняя настройки вручную.
                // process.env - хранит системные настройки вашего компьютера или сервера (переменные окружения)
                // NODE_ENV — это общемировой стандарт названия переменной, которая говорит, в каком режиме сейчас запущен сервер (development и production, разработка и производство соответственно
                // сравнение с === 'production', если 'false' - находится в режиме разработка
                // флаг secure: true - запрещает браузеру отправлять куку по обычному незащищенному протоколу http://. 
                // Браузер согласится отправить её только по зашифрованному протоколу https://. 
                // Если хакер попытается перехватить Wi-Fi трафик пользователя, он не сможет перехватить токен, потому что сеть будет требовать шифрование.
                // если жёстко написать 'secure: true' то во время разработки на домашнем пк куки в браузере создаваться не будут, а я потрачу кучу времени чтобы понять что не так

                maxAge: 3600000 // Срок жизни куки в миллисекундах (1 час, совпадает с JWT)
            }).send({ message: "Успешный вход в систему!" }); // Отправляем просто текстовый успех
    })


